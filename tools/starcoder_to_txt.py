#!/usr/bin/env python3
"""
starcoder_to_txt.py — превращает скачанный bigcode/starcoderdata (parquet / jsonl / jsonl.gz)
в обычные текстовые файлы для hashnet_proto: по одному файлу на язык (имя = имя папки языка).

  python3 starcoder_to_txt.py ПАПКА_С_ДАННЫМИ --out code_txt
  python3 starcoder_to_txt.py ПАПКА --out code_txt --only rust,python --max-gb-per-lang 3

Нужен pyarrow для parquet:  pip install pyarrow   (jsonl работает без него)

Фильтры (все можно отключить --no-filter): размер файла 200 Б..200 КБ, макс. длина строки <= 1000,
средняя <= 120, доля букв/цифр >= 0.25, пометки автогенерации (@generated, DO NOT EDIT, Code generated,
aws_smithy ...), точные дубликаты (по хешу). Между файлами ставится разделитель "\n<|eof|>\n",
чтобы модель училась границам файлов.
"""
import argparse, gzip, hashlib, json, os, sys, time

SEP = "\n<|eof|>\n"
GEN = ("@generated", "DO NOT EDIT", "Do not edit", "Code generated", "automatically generated",
       "auto-generated", "autogenerated", "This file was generated", "aws_smithy_http", "svd2rust", "bindgen")


def good(t, nofilter):
    n = len(t)
    if n < 200 or n > 200_000:
        return False
    if nofilter:
        return True
    head = t[:2000]
    if any(g in head for g in GEN):
        return False
    lines = t.split("\n")
    if max(map(len, lines)) > 1000 or n / max(len(lines), 1) > 120:
        return False
    alnum = sum(c.isalnum() for c in t[:20000])
    return alnum / min(n, 20000) >= 0.25


def rows(path):
    if path.endswith(".parquet"):
        import pyarrow.parquet as pq
        pf = pq.ParquetFile(path)
        col = "content" if "content" in pf.schema_arrow.names else pf.schema_arrow.names[0]
        for b in pf.iter_batches(batch_size=1000, columns=[col]):
            for s in b.column(0).to_pylist():
                if s:
                    yield s
    else:
        op = gzip.open if path.endswith(".gz") else open
        with op(path, "rt", encoding="utf-8", errors="ignore") as f:
            for line in f:
                try:
                    d = json.loads(line)
                except Exception:
                    continue
                s = d.get("content") or d.get("text")
                if s:
                    yield s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("--out", default="code_txt")
    ap.add_argument("--only", default="", help="языки через запятую (имена папок), по умолчанию все")
    ap.add_argument("--max-gb-per-lang", type=float, default=0)
    ap.add_argument("--no-filter", action="store_true")
    a = ap.parse_args()
    only = {x.strip().lower() for x in a.only.split(",") if x.strip()}
    os.makedirs(a.out, exist_ok=True)
    langs = {}
    for root, _, files in os.walk(a.src):
        for fn in sorted(files):
            if fn.endswith((".parquet", ".jsonl", ".jsonl.gz", ".json.gz")):
                lang = os.path.basename(root).lower() if os.path.abspath(root) != os.path.abspath(a.src) else "all"
                langs.setdefault(lang, []).append(os.path.join(root, fn))
    if not langs:
        sys.exit("Не нашёл ни .parquet, ни .jsonl(.gz) в " + a.src)
    seen = set()
    for lang, paths in sorted(langs.items()):
        if only and lang not in only:
            continue
        cap = int(a.max_gb_per_lang * 1e9) if a.max_gb_per_lang else 0
        out_p = os.path.join(a.out, lang + ".txt")
        kept = dropped = dup = 0
        written = 0
        t0 = time.time()
        with open(out_p, "w", encoding="utf-8", newline="\n") as o:
            for p in sorted(paths):
                for s in rows(p):
                    s = s.replace("\r\n", "\n").replace("\x00", "")
                    if not good(s, a.no_filter):
                        dropped += 1
                        continue
                    h = hashlib.blake2b(" ".join(s.split()).encode("utf-8", "ignore"), digest_size=12).digest()
                    if h in seen:
                        dup += 1
                        continue
                    seen.add(h)
                    o.write(s)
                    o.write(SEP)
                    written += len(s.encode("utf-8")) + len(SEP)
                    kept += 1
                    if cap and written >= cap:
                        break
                    if kept % 20000 == 0:
                        print(f"\r{lang}: {kept} файлов, {written/1e9:.2f} ГБ", end="", file=sys.stderr, flush=True)
                if cap and written >= cap:
                    break
        print(f"\r{lang:14} оставлено {kept:>8} файлов, {written/1e9:6.2f} ГБ | отброшено {dropped} | дубликатов {dup} | {time.time()-t0:.0f} с")


if __name__ == "__main__":
    main()
